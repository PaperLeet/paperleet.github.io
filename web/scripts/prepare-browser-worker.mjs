import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {build} from 'esbuild';

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// Bundle all worker helpers into one immutable identity. A helper change cannot
// accidentally reuse a calibration made by an earlier executing worker.
const compiled = await build({absWorkingDir:web,entryPoints:['src/browserWorker.mjs'],bundle:true,
  platform:'browser',format:'esm',target:'es2022',minify:true,write:false,logLevel:'silent'});
const bytes = compiled.outputFiles[0].contents;
const digest = createHash('sha256').update(bytes).digest('hex');
const asset = `browser-judge/worker-${digest}.mjs`;
await fs.mkdir(path.join(web,'public/browser-judge'),{recursive:true});
await fs.writeFile(path.join(web,'public',asset),bytes);
await fs.writeFile(path.join(web,'src/browserWorkerAsset.generated.ts'),
  `// Generated by prepare-browser-worker.mjs.\nexport const browserWorkerAsset = ${JSON.stringify(asset)};\nexport const browserWorkerDigest = ${JSON.stringify(digest)};\n`);
console.log(`Browser worker ready: ${bytes.length} bytes, ${digest.slice(0,12)}`);
