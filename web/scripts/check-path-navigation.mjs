import assert from 'node:assert/strict';
import fs from 'node:fs';
import React,{act} from 'react';
import {JSDOM} from 'jsdom';
import {createServer} from 'vite';

const dom=new JSDOM('<html data-routing="path"><head><title>PaperLeet</title></head><body><div id="root"></div></body></html>',{url:'https://paperleet.test/#/papers/flow-matching',pretendToBeVisual:true});
const globals={window:dom.window,document:dom.window.document,location:dom.window.location,history:dom.window.history,Element:dom.window.Element,HashChangeEvent:dom.window.HashChangeEvent,IS_REACT_ACT_ENVIRONMENT:true};
const previous=new Map(Object.keys(globals).map(key=>[key,Object.getOwnPropertyDescriptor(globalThis,key)]));
for(const [key,value] of Object.entries(globals))Object.defineProperty(globalThis,key,{value,writable:true,configurable:true});
const server=await createServer({server:{middlewareMode:true,hmr:false,ws:false},appType:'custom',optimizeDeps:{noDiscovery:true,include:[]}});
let root;
try {
  const {startPathNavigation}=await server.ssrLoadModule('/src/pathNavigation.ts');
  const {appLocation,publicHref,registerCatalogRoutes,routeHash,sameAppUrl}=await server.ssrLoadModule('/src/appLocation.ts');
  const {default:AppLink}=await server.ssrLoadModule('/src/AppLink.tsx');
  const {createRoot}=await import('react-dom/client');
  const catalog=JSON.parse(fs.readFileSync('public/data/catalog.json','utf8'));
  const problem=catalog.problems.find(row=>row.paper_id==='flow-matching');
  startPathNavigation();registerCatalogRoutes(catalog.problems);
  document.dispatchEvent(new window.CustomEvent('paperleet:catalog',{detail:catalog}));
  assert.equal(location.pathname,'/papers/flow-matching/');assert.equal(location.hash,'');
  assert(document.title.includes('Flow Matching'));assert(document.title.includes('Python Implementation'));
  assert.equal(document.querySelector('link[rel="canonical"]').href,'https://paperleet.com/papers/flow-matching/');
  assert.equal(publicHref('#/lists/llm-basics'),'/collections/llm-basics/');
  assert.equal(publicHref('#/community/demo'),'/#/community/demo');
  assert.equal(publicHref('#section'),'#section');
  assert.equal(routeHash('https://paperleet.test/#section'),'#');
  assert.equal(routeHash('https://paperleet.test/papers/flow-matching/#section'),'#/papers/flow-matching');
  assert.equal(publicHref('https://other.test/#/10'),'https://other.test/#/10');
  assert(!sameAppUrl(new URL('https://other.test/probelems/rl/ppo/')));
  assert(!sameAppUrl(new URL('https://paperleet.test/unrelated/#/community')));
  const href=`#/${problem.number}?from=collections%2Fdiffusion`,expected=`/problems/${problem.id}/?from=collections%2Fdiffusion`;
  root=createRoot(document.querySelector('#root'));
  await act(async()=>root.render(React.createElement(AppLink,{href},'Practice')));
  const anchor=document.querySelector('a');assert.equal(anchor.getAttribute('href'),expected);
  let capture;
  document.addEventListener('click',()=>{capture=appLocation.hash;},{once:true});
  await act(async()=>anchor.click());
  assert.equal(capture,'#/papers/flow-matching','Reading-position handlers run before navigation');
  assert.equal(location.pathname,`/problems/${problem.id}/`);assert.equal(location.hash,'');
  assert.equal(appLocation.hash,href);assert.equal(routeHash(anchor.href),href);
  assert(document.title.includes(problem.translations.en.title));
  assert.equal(document.querySelector('link[rel="canonical"]').href,`https://paperleet.com/problems/${problem.id}/`);
  const settle=()=>new Promise(resolve=>setTimeout(resolve,25));
  history.back();await settle();assert.equal(location.pathname,'/papers/flow-matching/');
  assert(document.title.includes('Python Implementation'));
  history.forward();await settle();assert.equal(location.pathname,`/problems/${problem.id}/`);
  appLocation.hash='#/community';assert.equal(location.pathname,'/');assert.equal(location.hash,'#/community');assert.equal(document.title,'PaperLeet');
  appLocation.hash=href;assert.equal(location.pathname,`/problems/${problem.id}/`);
  location.hash='#/papers/ppo';await settle();assert.equal(location.pathname,'/papers/ppo/');assert.equal(location.hash,'');
  let routeEvents=0;const countRoute=()=>{routeEvents++;};window.addEventListener('hashchange',countRoute);
  location.hash='#section';await settle();assert.equal(location.hash,'#section');assert.equal(appLocation.hash,'#/papers/ppo');
  registerCatalogRoutes(catalog.problems);assert.equal(location.hash,'#section');
  history.back();await settle();assert.equal(location.pathname,'/papers/ppo/');assert.equal(location.hash,'');
  history.forward();await settle();assert.equal(location.hash,'#section');assert.equal(routeEvents,0,'Document anchors do not reset application route state');
  window.removeEventListener('hashchange',countRoute);
  await act(async()=>root.render(React.createElement(AppLink,{href,onClick:event=>event.preventDefault()},'Prevented')));
  await act(async()=>document.querySelector('a').click());assert.equal(location.pathname,'/papers/ppo/');
  await act(async()=>root.render(React.createElement(AppLink,{href},'New tab')));
  const modified=new window.MouseEvent('click',{bubbles:true,cancelable:true,ctrlKey:true});
  const preventNative=event=>event.preventDefault();window.addEventListener('click',preventNative,{once:true});
  document.querySelector('a').dispatchEvent(modified);assert.equal(location.pathname,'/papers/ppo/');
  console.log('PASS path navigation: real hrefs, legacy bookmarks, deep links, context, metadata, click order, history, document anchors and dynamic-route compatibility');
} finally {
  if(root)await act(async()=>root.unmount());await server.close();dom.window.close();
  for(const [key,value] of previous)if(value)Object.defineProperty(globalThis,key,value);else delete globalThis[key];
}
